"""Research-log entries: their YAML header is the one official record of decisions; stage gates read it.

research_log/entries/2026-10-21_warmup-variance.md:
    ---
    experiment: warmup_variance
    sweeps:                       # appended by `just decide`, never by hand
    - id: pilot_20261021-091500
      decision: GO
      ...
    ---
    # Title
    ...
"""

import datetime as dt
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

VERDICTS = ("GO", "NO_GO", "INCONCLUSIVE")
STAGES = ("sanity", "pilot", "confirm", "final")
GATES = {"confirm": "pilot", "final": "confirm"}  # stage -> stage that must have been decided GO


class GateError(RuntimeError):
    pass


@dataclass
class Entry:
    path: Path
    header: dict[str, Any]
    body: str

    @property
    def experiment(self) -> str:
        return str(self.header.get("experiment", ""))

    @property
    def sweeps(self) -> list[dict[str, Any]]:
        return list(self.header.get("sweeps") or [])

    def save(self) -> None:
        header = yaml.safe_dump(self.header, sort_keys=False, allow_unicode=True)
        self.path.write_text(f"---\n{header}---\n{self.body}")


def read_entry(path: Path) -> Entry:
    text = path.read_text()
    if not text.startswith("---\n"):
        return Entry(path, {}, text)
    header, body = text[4:].split("\n---\n", 1)
    return Entry(path, yaml.safe_load(header) or {}, body)


def entries(log_dir: Path) -> list[Entry]:
    return [read_entry(p) for p in sorted((log_dir / "entries").glob("*.md"))]


def find_entry(log_dir: Path, experiment: str) -> Entry | None:
    found = [e for e in entries(log_dir) if e.experiment == experiment]
    if len(found) > 1:
        raise GateError(f"several log entries claim experiment {experiment!r}: {[str(e.path) for e in found]}")
    return found[0] if found else None


def check_gate(log_dir: Path, experiment: str, stage: str) -> None:
    if stage not in STAGES:
        raise ValueError(f"stage must be one of {STAGES}, got {stage!r}")
    needed = GATES.get(stage)
    if needed is None:
        return
    entry = find_entry(log_dir, experiment)
    if entry is None or not any(s.get("stage") == needed and s.get("decision") == "GO" for s in entry.sweeps):
        raise GateError(
            f"stage {stage!r} needs a {needed!r} sweep of {experiment!r} decided GO in its log entry "
            f"({'none found' if entry is None else entry.path}). Record it with `just decide`."
        )


def decide(log_dir: Path, sweep: dict[str, Any], counts: dict[str, int], verdict: str, reason: str) -> Entry:
    if verdict not in VERDICTS:
        raise ValueError(f"verdict must be one of {VERDICTS}")
    entry = find_entry(log_dir, sweep["experiment"])
    if entry is None:
        raise GateError(f"no log entry with `experiment: {sweep['experiment']}`; create one with `just new-experiment`")
    if any(s.get("id") == sweep["id"] for s in entry.sweeps):
        raise GateError(f"sweep {sweep['id']} is already decided in {entry.path}; decisions are final")
    n = sum(counts.values())
    entry.header["sweeps"] = [
        *entry.sweeps,
        {
            "id": sweep["id"],
            "stage": sweep["stage"],
            "commit": sweep["commit"][:12],
            "decision": verdict,
            "reason": reason,
            "members": f"{counts.get('DONE', 0)}/{n} done"
            + "".join(f", {counts[s]} {s.lower()}" for s in ("FAILED", "STARTED", "MISSING") if counts.get(s)),
            "decided": dt.date.today().isoformat(),
        },
    ]
    entry.save()
    write_index(log_dir)
    return entry


def write_index(log_dir: Path) -> Path:
    rows = ["| Entry | Experiment | Decisions |", "|---|---|---|"]
    for e in entries(log_dir):
        decisions = "<br>".join(f"{s['stage']} `{s['id']}`: **{s['decision']}**" for s in e.sweeps) or "—"
        rows.append(f"| [{e.path.stem}](entries/{e.path.name}) | `{e.experiment}` | {decisions} |")
    path = log_dir / "README.md"
    path.write_text(
        "# Research log\n\nGenerated by `just log-index` (and `just decide`); do not edit.\n"
        "Session diary: [track_record.md](track_record.md) · backlog: GitHub issues labelled `idea` · "
        "deferred and future work: [deferred.md](deferred.md) · design decisions: [decisions/](decisions/)\n\n"
        + "\n".join(rows)
        + "\n"
    )
    return path


def new_entry(log_dir: Path, experiment: str, title: str, notebook: str) -> Entry:
    path = log_dir / "entries" / f"{dt.date.today().isoformat()}_{experiment.replace('_', '-')}.md"
    entry = Entry(
        path,
        {"experiment": experiment, "sweeps": []},
        f"# {title}\n\n## Question\n\nSee the description at the top of `{notebook}`; not retyped here.\n\n"
        f"## §1 Sanity ({dt.date.today().isoformat()})\n\nWhat ran, the result (numbers from the snapshot), "
        "interpretation, next step.\n",
    )
    entry.save()
    return entry
